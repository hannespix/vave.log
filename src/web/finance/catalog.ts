export type FinanceKey = keyof typeof catalog;
export function ft(locale: InvoiceLanguage, key: FinanceKey): string {
  return catalog[key][locale === "de" ? 1 : locale === "zh" ? 2 : 0];
}
export function financeError(error: unknown, locale: InvoiceLanguage) {
  const code =
    typeof error === "object" && error !== null && "code" in error
      ? String(error.code)
      : "error";
  return ft(
    locale,
    (
      [
        "validation",
        "logo_invalid",
        "forbidden",
        "not_found",
        "conflict",
        "missing_configuration",
        "result_limit",
        "time_entry_limit",
        "result_incomplete",
      ] as string[]
    ).includes(code)
      ? (code as FinanceKey)
      : "error",
  );
}
